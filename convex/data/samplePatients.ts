  insurance: string;
  status: "active" | "discharged" | "scheduled";
  condition: string;
  chronicConditions: string[];
  allergies: { substance: string; reaction: string; severity: string }[];
  medications: { name: string; dose: string; frequency: string; indication?: string; sinceDaysAgo?: number }[];
  vitals: {
    daysAgo: number;
    bloodPressure: string;
    heartRate: number;
    temperatureC: number;
    respiratoryRate: number;
    spo2: number;
    weightKg: number;
    heightCm: number;
  };
  labs: { test: string; value: string; unit: string; referenceRange: string; daysAgo: number; flag?: string }[];
  visits: { daysAgo: number; reason: string; diagnosis: string; notes: string }[];
  immunizations: string[];
  socialHistory: string;
  familyHistory: string;
  notes: string;
  symptoms: { name: string; days: string }[];
